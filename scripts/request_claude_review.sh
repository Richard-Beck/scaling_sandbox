#!/usr/bin/env bash
# Request an independent Claude review of committed manuscript work.
#
# Usage:
#   scripts/request_claude_review.sh --target <name> --commit <rev> \
#       [--baseline <rev>] [--] <changed deliverable path>...
#
# The request passed to Claude is facts only (target, commits, paths); there is
# deliberately no field for rationale. Prints the review path, then runs the
# review in the foreground. Exit 0 only if the review file was written.
#
# Environment overrides: CLAUDE_REVIEW_MODEL (default claude-opus-5-5),
# CLAUDE_REVIEW_EFFORT (default high).
set -euo pipefail

usage() { sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-2}"; }

target="" commit="" baseline=""
paths=()
while (($#)); do
  case "$1" in
    --target) target="${2:?}"; shift 2 ;;
    --commit) commit="${2:?}"; shift 2 ;;
    --baseline) baseline="${2:?}"; shift 2 ;;
    -h|--help) usage 0 ;;
    --) shift; paths+=("$@"); break ;;
    -*) echo "unknown option: $1" >&2; usage ;;
    *) paths+=("$1"); shift ;;
  esac
done
[[ -n "$target" && -n "$commit" ]] || usage

root="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
cd "$root"

commit="$(git rev-parse --verify --quiet "${commit}^{commit}")" \
  || { echo "not a commit: $commit" >&2; exit 2; }
if [[ -n "$baseline" ]]; then
  baseline="$(git rev-parse --verify --quiet "${baseline}^{commit}")" \
    || { echo "not a commit: $baseline" >&2; exit 2; }
fi
head="$(git rev-parse HEAD)"

slug="$(printf '%s' "$target" | tr -cs 'A-Za-z0-9._-' '_' | sed 's/^_*//; s/_*$//')"
[[ -n "$slug" ]] || { echo "target gives an empty file name" >&2; exit 2; }
stem="reviews/claude/$(date +%Y%m%d)_${slug}"
review="${stem}.md"
n=2
while [[ -e "$review" ]]; do review="${stem}_${n}.md"; n=$((n + 1)); done
mkdir -p reviews/claude/logs
log="reviews/claude/logs/$(basename "${review%.md}").json"

path_lines="" dirty_lines=""
for p in "${paths[@]}"; do
  path_lines+="- ${p}"$'\n'
  if [[ -n "$(git status --porcelain -- "$p" 2>/dev/null)" ]]; then
    dirty_lines+="- ${p}"$'\n'
  fi
done
[[ -n "$path_lines" ]] || path_lines="- (none listed)"$'\n'
[[ -n "$dirty_lines" ]] || dirty_lines="- (none)"$'\n'

request="Review request (headless; generated by scripts/request_claude_review.sh)

Target: ${target}
Commit to review: ${commit}
Baseline commit: ${baseline:-(not given; determine per the skill)}
Working-tree HEAD at launch: ${head}$([[ "$head" == "$commit" ]] || printf ' (differs from the commit to review)')
Write the review to: ${review}

Changed deliverables as listed by the requester (verify against the diff):
${path_lines}
Listed paths with uncommitted changes at launch:
${dirty_lines}
Follow .claude/skills/manuscript-review/SKILL.md, including its headless
section. Nobody is available to answer questions during this run."

echo "Review file: ${review}"
echo "Log: ${log}"

status=0
claude -p "$request" \
  --model "${CLAUDE_REVIEW_MODEL:-claude-opus-5-5}" \
  --effort "${CLAUDE_REVIEW_EFFORT:-high}" \
  --permission-mode dontAsk \
  --permission-prompts none \
  --output-format json \
  --allowedTools \
    "Read" "Skill" \
    "Write(./reviews/claude/**)" "Edit(./reviews/claude/**)" \
    "Bash(git log *)" "Bash(git diff *)" "Bash(git show *)" \
    "Bash(git status *)" "Bash(git ls-files *)" "Bash(git rev-parse *)" \
    "Bash(git ls-tree *)" "Bash(ls *)" "Bash(grep *)" "Bash(file *)" \
  > "$log" || status=$?

if [[ -s "$review" ]]; then
  echo "Review written: ${review}"
  exit "$status"
fi
echo "No review written (claude exit ${status}); see ${log}" >&2
exit 1
